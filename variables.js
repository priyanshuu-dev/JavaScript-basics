// variables.js
// Learning JavaScript Variables

// Using var (old way)
var name = "Priyanshu";
console.log("Using var:", name);

// Using let (can be updated)
let age = 20;
console.log("Age:", age);

age = 21; // updating value
console.log("Updated Age:", age);

// Using const (cannot be changed)
const country = "India";
console.log("Country:", country);

// Different data types
let isStudent = true;
let marks = 85.5;

console.log("Is Student:", isStudent);
console.log("Marks:", marks);