// if-else.js
// Learning If-Else Conditions

let marks = 75;

// Basic if-else
if (marks >= 50) {
    console.log("You Passed!");
} else {
    console.log("You Failed!");
}

// if-else if ladder
if (marks >= 90) {
    console.log("Grade: A");
} else if (marks >= 75) {
    console.log("Grade: B");
} else if (marks >= 60) {
    console.log("Grade: C");
} else {
    console.log("Grade: D");
}

// Example with user age
let age = 18;

if (age >= 18) {
    console.log("You can vote.");
} else {
    console.log("You cannot vote.");
}
